# ===== МАГАЗИН =====
def магазин():
    global деньги, гитара

    print("\n🛒 МАГАЗИН ГИТАР:")
    for i, (название, данные) in enumerate(ИНСТРУМЕНТЫ.items(), 1):
        статус = "✅" if гитара == название else "💰"
        print(f"{статус} {i}. {название} — {данные['цена']} (бонус x{данные['бонус']})")
    print("0. Назад")

    try:
        выбор = int(input("Что купить? "))
        if выбор == 0:
            return
        название = list(ИНСТРУМЕНТЫ.keys())[выбор - 1]
        if гитара == название:
            print("✅ У тебя уже есть эта гитара!")
            return
        цена = ИНСТРУМЕНТЫ[название]["цена"]
        if деньги >= цена:
            деньги -= цена
            гитара = название
            print(f"🎸 Куплена: {название}!")
        else:
            print(f"❌ Не хватает {цена - деньги} денег!")
    except (ValueError, IndexError):
        print("❌ Ошибка!")


