def выступить():
    global деньги, фанаты, слава, энергия, всего_выступлений, идеальных_игр, провалов

    if энергия < 20:
        print("❌ Филя устал! Нужен отдых!")
        return

    if not репертуар:
        print("❌ У Фили нет песен! Напиши песню (пункт 6)!")
        return

    print("\n🎤 КАКУЮ ПЕСНЮ ИГРАТЬ?")
    for i, песня in enumerate(репертуар, 1):
        данные = ПЕСНИ.get(песня, {})
        сложность = данные.get("сложность", 0.5)
