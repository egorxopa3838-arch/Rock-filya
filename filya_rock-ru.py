def играть_альбом():
    global деньги, фанаты, слава, энергия, всего_выступлений, идеальных_игр, провалов, альбомов_сыграно

    if энергия < 50:
        print("❌ Филя устал! Нужно 50 энергии!")
        return

    доступные = {}
    for имя, данные in АЛЬБОМЫ.items():
        if all(п in репертуар for п in данные["песни"]):
            доступные[имя] = данные

    if not доступные:
        print("❌ Нет доступных альбомов! Выучи все песни из альбома!")
        return

    print("\n📀 ДОСТУПНЫЕ АЛЬБОМЫ:")
    for i, (имя, данные) in enumerate(доступные.items(), 1):
        print(f"  {i}. {имя}")
        print(f"     {данные['описание']}")
        print(f"     Песни: {', '.join(данные['песни'])}")
        print(f"     Бонус: +{данные['бонус_слава']} славы, +{данные['бонус_деньги']} денег")

    try:
        выбор = int(input("\nКакой альбом? (0 - отмена): "))
        if выбор == 0:
            return
        имя_альбома = list(доступные.keys())[выбор - 1]
    except (ValueError, IndexError):
        print("❌ Ошибка!")
        return

    альбом = доступные[имя_альбома]

    print(f"\n📀 ФИЛЯ ИГРАЕТ АЛЬБОМ: {имя_альбома}")
    print("=" * 50)
    time.sleep(2)

    успешно = 0
    идеально = 0

    for песня in альбом["песни"]:
        данные = ПЕСНИ[песня]
        сложность = данные["сложность"]
        бонус_гитары = ИНСТРУМЕНТЫ[гитара]["бонус"]
        шанс = min(0.95, сложность + (бонус_гитары - 1) * 0.05)

        print(f"\n🎵 Играет: {песня}...")
        time.sleep(1)

        успех = random.random()
        всего_выступлений += 1

        if успех < шанс * 0.3:
            print("  🎉🎉🎉 ИДЕАЛЬНО! 🎉🎉🎉")
            идеально += 1
            успешно += 1
        elif успех < шанс:
            print("  🎉 Успешно!")
            успешно += 1
        else:
            print("  😱 Провал!")
            провалов += 1

    print(f"\n{'=' * 50}")
    print(f"📀 РЕЗУЛЬТАТ АЛЬБОМА: {успешно}/{len(альбом['песни'])} успешно, {идеально} идеально")

    if успешно == len(альбом["песни"]):
        print("🎉🎉🎉 ВЕСЬ АЛЬБОМ СЫГРАН! 🎉🎉🎉")
        бонус_деньги = альбом["бонус_деньги"] * ИНСТРУМЕНТЫ[гитара]["бонус"]
        деньги += бонус_деньги
        фанаты += 50 * ИНСТРУМЕНТЫ[гитара]["бонус"]
        слава += альбом["бонус_слава"]
        альбомов_сыграно += 1
        print(f"💰 +{бонус_деньги} денег (бонус альбома!)")
        print(f"👥 +{50 * ИНСТРУМЕНТЫ[гитара]['бонус']} фанатов")
        print(f"⭐ +{альбом['бонус_слава']} славы")
        print(f"🏆 ДОСТИЖЕНИЕ: Альбом {имя_альбома} сыгран!")
    else:
        print(f"😐 Альбом сыгран не полностью. Попробуй ещё!")

